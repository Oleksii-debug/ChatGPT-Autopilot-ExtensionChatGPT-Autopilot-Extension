"""Real native-model bank preparation -> public package install -> fast_clip.

Development-only software probe. NVDA imports use the test import surface; no
WavePlayer, output device, fake speech model, or audible-onset claim is involved.
The waveform is generated by the actual native ONNX carrier and OpenVoice
selected-voice projection. Prepared lookups are then timed with model creation
and subprocess startup explicitly forbidden.
"""
from __future__ import annotations

import argparse
from datetime import datetime,timezone
from functools import cached_property
from hashlib import sha256
import importlib.util
import json
from pathlib import Path
import statistics
import sys
from threading import Event,Timer
from time import perf_counter,perf_counter_ns
from unittest.mock import patch
import wave


ROOT=Path(__file__).resolve().parents[1]
RUNTIME=ROOT/"source/0.12.2/kx47Runtime"


def load(name,path):
    spec=importlib.util.spec_from_file_location(name,path)
    module=importlib.util.module_from_spec(spec)
    sys.modules[name]=module
    try:spec.loader.exec_module(module)
    except Exception:
        sys.modules.pop(name,None)
        raise
    return module


def file_digest(path):
    digest=sha256()
    with Path(path).open("rb") as stream:
        while block:=stream.read(4*1024*1024):digest.update(block)
    return digest.hexdigest()


def timing(values):
    ordered=sorted(values)
    return {"count":len(values),"minimum_ms":ordered[0],"median_ms":statistics.median(values),
            "p95_ms":ordered[(len(values)*95+99)//100-1],
            "p99_ms":ordered[(len(values)*99+99)//100-1],"maximum_ms":ordered[-1]}


def run(args):
    output=Path(args.output).resolve()
    if output.exists():raise ValueError("Choose a new probe output directory")
    models=Path(args.models_root).resolve()
    if output.is_relative_to(models):raise ValueError("The probe cannot write inside model resources")
    output.mkdir(parents=True)
    sys.path.insert(0,str(RUNTIME))
    import numpy as np
    import onnxruntime as ort
    ort.disable_telemetry_events()
    import voice_assets
    from session_control import GuardedSession,SynthesisCancelled,cancel_running
    from wide_voice import WideVoices
    preparation=load("_fast_bank_preparation",ROOT/"tools/prepare_voice_banks.py")
    packages=load("_fast_bank_package_cli",ROOT/"tools/voice_packages.py")
    probe=load("_fast_bank_worker_helpers",ROOT/"tools/windows_engine_probe.py")
    preferences=load("_fast_bank_preferences",RUNTIME/"preferences.py")
    surfaces=load("_fast_bank_nvda_import_surface",ROOT/"tests/nvda_stubs.py")
    source=RUNTIME/"models/CharacterNames"/(args.language+".json")
    document=json.loads(source.read_text(encoding="utf-8"))
    jobs=preparation.load_entries_document(document)
    requested=args.keys.split(",")
    selected=[]
    for key in requested:
        row=next((row for row in jobs if row["lookup_text"]==key and row.get("source_kind")=="letter_name"),None)
        if row is None or row["semantic_kind"]!="spoken_name":
            raise ValueError("No source-backed ordinary letter name is available for "+key)
        selected.append(row)
    opened=[]

    class Owner:
        def __init__(self):self.cancel_event=Event()
        def check_cancelled(self):
            if self.cancel_event.is_set():raise SynthesisCancelled()
    owner=Owner()

    class Projector:
        def _session(self,path):
            options=ort.SessionOptions()
            options.intra_op_num_threads=2;options.inter_op_num_threads=1
            options.add_session_config_entry("session.intra_op.allow_spinning","0")
            opened.append(str(path))
            return GuardedSession(ort.InferenceSession(str(path),sess_options=options,
                providers=["CPUExecutionProvider"]),owner)
        @cached_property
        def flow(self):return self._session(models/"OpenVoiceV2/encoder-flow.onnx")
        @cached_property
        def decoder(self):return self._session(models/"OpenVoiceV2/decoder.onnx")
        def target_profile(self,profile):
            path=next(prepared/name for name,role in recipe["roles"].items() if role=="target_embedding")
            target=np.load(path,allow_pickle=False)
            if target.shape!=(1,256,1) or not np.isfinite(target).all():raise ValueError("Invalid selected target profile")
            return target
        @staticmethod
        def levelled(chunks):yield from chunks
    projector=Projector()
    voices=WideVoices(models,models/"voices",owner=owner,converter=projector)

    class RealRenderer:
        def render(self,request,timeout):
            if request["profile"]!=args.voice or request["language"]!=args.language:
                raise ValueError("Probe requested another voice/language")
            event=Event();owner.cancel_event=event
            def cancel():
                event.set();cancel_running(owner,event)
            timer=Timer(timeout,cancel);timer.daemon=True;timer.start()
            started=perf_counter();first=None;blocks=[]
            try:
                for block in voices.blocks(request["profile"],request["language"],request["text"],
                                           request["speed"],request["character"]):
                    if first is None:first=(perf_counter()-started)*1000
                    blocks.append(block)
            finally:timer.cancel()
            audio=np.concatenate(blocks) if blocks else np.empty(0,np.float32)
            pcm=np.rint(np.clip(audio,-1,1)*32767).astype("<i2").tobytes()
            return pcm,{"first_pcm_ms":first,"completed_ms":(perf_counter()-started)*1000,
                        "renderers":[{"profile":args.voice,"speaker":args.voice,
                                      "engine":"real-native-plus-openvoice","code":args.language}],
                        "scope":"real Linux direct model adapter, not Windows worker pipe or NVDA output"}

    prepared=output/"prepared-source"
    prepared.mkdir()
    recipe=preparation.copy_profile_source(models.parent,voice_assets,args.voice,prepared,version=args.version,
        license_text="Original supplied profile terms and upstream native model notices; technical candidate only, no new rights asserted")
    recipe["languages"]=[args.language]
    roles,generation=preparation.generate_banks(RealRenderer(),probe,args.voice,selected,prepared/"banks",timeout=args.timeout)
    recipe["roles"].update({"banks/"+name:role for name,role in roles.items()})
    (prepared/"recipe.json").write_text(json.dumps(recipe,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    manifest=packages.prepare_manifest(prepared,**recipe)
    package=output/(args.voice+"-"+args.version+".dordiai-voice")
    packages.create_package(prepared,manifest,package)
    installed=output/"installed-voices"
    install_result=preferences.install_extra_package(package,output/"probe-addon",references=installed,engine_id="holos")
    voice_assets.clear_cache()
    voices.close()
    projector.__dict__.pop("flow",None);projector.__dict__.pop("decoder",None)
    opened_before=list(opened)
    report={"format":"dordiai-real-prepared-fast-bank-probe","format_version":1,
            "created_utc":datetime.now(timezone.utc).isoformat(),"status":"running",
            "scope":"real native audio -> package create/install -> actual driver planning/fast_clip, with NVDA import stubs only",
            "voice":args.voice,"language":args.language,"version":args.version,
            "source_document":str(source.relative_to(ROOT)),"source_document_sha256":file_digest(source),
            "name_source":document.get("sources",{}).get("curated_primary_alphabet_names"),
            "model_files_sha256":{str(path.relative_to(models)):file_digest(path) for path in (
                models/"MMS"/args.language/"model.onnx",models/"MMS"/args.language/"source.npy",
                models/"OpenVoiceV2/encoder-flow.onnx",models/"OpenVoiceV2/decoder.onnx")},
            "prepared_target_sha256":next(data["sha256"] for data in manifest["files"].values()
                                          if data.get("role")=="target_embedding"),
            "generation":generation,"package_file":package.name,"package_bytes":package.stat().st_size,
            "package_sha256":file_digest(package),"install_result":install_result,
            "nvda_verified":False,"physical_audio_verified":False,"pronunciation_verified":False,
            "only_representative_names":True,"all_letters_or_languages_verified":False,"lookups":[]}
    with surfaces.driver_module() as driver:
        synth=driver.SynthDriver.__new__(driver.SynthDriver)
        synth._dordiai_init();synth._models=models
        synth._language_catalog=driver._runtime_module("language_catalog")
        synth._managedVoices=voice_assets.discover_voices(installed,engine_id="holos")
        synth._voices={args.voice:(args.voice,args.voice,"reference","en-US")};synth._voice=args.voice
        synth._compatibleVoiceCache={};synth._installedLanguageCache=None;synth._canJoin=True
        state=driver._prefs.load_preference_state({"dordiaiEnabledLanguages":args.language,
            "dordiaiDefaultLanguage":args.language,"dordiaiLanguageVoices":json.dumps({args.language:args.voice})},
            synth._dordiai_all_voices(),synth._dordiai_all_languages(),synth._dordiai_compatible_voices)
        synth._dordiai_selection=state["selection"];synth._dordiai_enabled_languages=state["enabled_languages"]
        synth._dordiai_mode=state["mode"];synth._dordiai_voice_map=state["voice_map"]
        worker=driver.SpeechWorker(sys.executable,"must-not-start.py",models,(models/"Holos",installed,"holos"))
        with patch.object(driver.subprocess,"Popen",side_effect=AssertionError("Prepared lookup started a model worker")),\
             patch.object(ort,"InferenceSession",side_effect=AssertionError("Prepared lookup opened a model")):
            for row in selected:
                parts=list(synth._planned_parts([driver.LangChangeCommand(args.language),driver.CharacterModeCommand(True),row["lookup_text"]],
                    args.voice,"reference","en-US",50,{"pitch":50,"timbre":50,"volume":100},{},1,True,native_profiles=True))
                requests=[request for kind,request in parts if kind=="character"]
                if len(requests)!=1:raise AssertionError("Glyph did not plan as one character request")
                request=requests[0]
                if request["profile"]!=args.voice or request["language"]!=args.language:raise AssertionError("Wrong planned identity/language")
                started=perf_counter_ns();pcm=worker.fast_clip(request);initial_ms=(perf_counter_ns()-started)/1e6
                if not pcm or not any(pcm):raise AssertionError("Prepared bank returned no audible data")
                values=[]
                for _ in range(args.repetitions):
                    started=perf_counter_ns();again=worker.fast_clip(request);values.append((perf_counter_ns()-started)/1e6)
                    if again!=pcm:raise AssertionError("Prepared PCM changed across identical requests")
                filename=args.language+"-"+row["lookup_text"]+"-"+args.voice+".wav"
                path=output/filename
                with wave.open(str(path),"wb") as stream:
                    stream.setnchannels(1);stream.setsampwidth(2);stream.setframerate(24000);stream.writeframes(pcm)
                report["lookups"].append({"lookup_text":row["lookup_text"],"spoken_name":row["text"],
                    "planned_request":request,"first_lookup_ms":initial_ms,"warm_lookup":timing(values),
                    "pcm_sha256":sha256(pcm).hexdigest(),"wave_file":filename,"wave_bytes":path.stat().st_size,
                    "wave_sha256":file_digest(path),"audio":probe.audio_statistics(pcm)})
        report["model_worker_started_for_lookup"]=worker._process is not None
        report["new_model_sessions_for_lookup"]=len(opened)-len(opened_before)
        worker.close()
    report["status"]="passed"
    report["meets_20ms_software_lookup_p95"]=all(row["warm_lookup"]["p95_ms"]<=20 for row in report["lookups"])
    report["timing_limit"]="Function return of prepared PCM only; no physical/audible/NVDA latency claim"
    (output/"report.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    return report


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models-root",required=True,type=Path)
    parser.add_argument("--output",required=True,type=Path)
    parser.add_argument("--voice",default="viktoriia")
    parser.add_argument("--language",default="ha")
    parser.add_argument("--keys",default="b,d,k")
    parser.add_argument("--version",default="0.13.1-probe.1")
    parser.add_argument("--repetitions",type=int,default=100)
    parser.add_argument("--timeout",type=float,default=90)
    args=parser.parse_args(argv)
    if not 100<=args.repetitions<=10000 or not 0<args.timeout<=600:
        parser.error("Use100..10000 repetitions and0..600 seconds timeout")
    report=run(args)
    print(json.dumps({"status":report["status"],"lookups":[(row["lookup_text"],row["warm_lookup"]["p95_ms"]) for row in report["lookups"]],
                      "report":str(args.output/"report.json")},ensure_ascii=False))
    return 0


if __name__=="__main__":raise SystemExit(main())
